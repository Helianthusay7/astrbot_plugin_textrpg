def render_menu(player: Any = None, item_db: dict | None = None) -> str:
    """生成指令菜单。

    有角色时会在顶部给出「你现在该做什么」的指引 ——
    比单纯罗列指令有用得多。
    """
    lines = ["📜 道途指令总览", ""]

    tip = _next_step(player, item_db)
    if tip:
        lines.append(f"👉 {tip}")
        lines.append("")

    for group, desc, cmds in MENU_GROUPS:
        head = f"【{group}】"
        if desc:
            head += f" {desc}"
        lines.append(head)
        for cmd, note in cmds:
            lines.append(f"　{cmd:<12}{note}")
        lines.append("")

    lines.append("发送 /简介 看完整玩法说明")
    return "\n".join(lines).rstrip()


def _next_step(player: Any, item_db: dict | None) -> str:
    """根据玩家状态给一条「下一步做什么」的建议。

    这是菜单里最有价值的一行 —— 玩家最常问的不是「有哪些指令」，
    而是「我现在该干嘛」。
    """
    if player is None:
        return "你还没有角色，发送 /报名 创建一个。"

    try:
        from . import realm as realm_mod

        qi_now, qi_need = realm_mod.qi_progress(player.turns, player.exp)
        if qi_need <= 0:
            return "修为已圆满，发送 /突破 渡劫飞升。"

        # 血量过低先提醒恢复
        max_hp = player.max_hp(item_db or {})
        if max_hp > 0 and player.hp / max_hp < 0.3:
            return f"你只剩 {player.hp}/{max_hp} 气血，发送 /恢复 或 /闭关 休整。"

        # 没穿满装备就去历练
        if player.equipped_count() < 5:
            return "还有空装备位，发送 /历练 打怪掉落装备。"

        if len(getattr(player, "equipped_scriptures", []) or []) == 0:
            return "还没装配秘典，发送 /大道 看看学了哪些。"

        return f"修为 {qi_now}/{qi_need}，发送 /闭关 或 /历练 继续修行。"
    except Exception:
        # 菜单是「绝不能崩」的东西：取不到状态就给一句通用建议
        return "发送 /闭关 攒修为，/历练 打怪。"


